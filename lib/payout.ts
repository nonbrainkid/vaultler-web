/**
 * Дележ недельного пула между местами 1–10 (решение 2026-07-26, docs/roadmap.md).
 *
 *   доля(N) = (11 − N) / 55
 *
 * Вес места — `11 − место`, сумма весов всегда 55. Формула выбрана не только за форму
 * кривой, но и за проверяемость: игрок должен уметь посчитать свою долю в уме и не верить
 * нам на слово. По той же причине проценты на сайте считаются ЗДЕСЬ, а не вписаны в
 * разметку руками — иначе страница однажды разойдётся с документом и с тем, что реально
 * выплачено.
 *
 * Почему линейно, а не круче: при слишком крутой кривой места 6–10 перестают что-либо
 * значить, и обещание «десять мест оплачиваются» превращается в обман. При слишком
 * плоской пропадает смысл драться за первое.
 *
 * Деньги отсюда НЕ уходят: модуль только считает доли для показа и для сверки при ручной
 * выплате. Автоматических переводов в проекте нет by design (docs/security.md).
 */

/** Сколько мест в деньгах. */
export const PAYOUT_SEATS = 10;

/** Веса мест 1…10: 10, 9, … 1. Сумма — 55. */
export const PAYOUT_SHARES: readonly number[] = Array.from(
  { length: PAYOUT_SEATS },
  (_, i) => PAYOUT_SEATS - i,
);

/**
 * Доля места в пуле как множитель (0…1).
 *
 * `seats` — фактическое число мест: если на борде меньше десяти игроков, веса
 * перенормируются на то, что есть (вес места N = seats + 1 − N). Иначе часть пула
 * оказалась бы «ничьей», а объявлять её и не платить — хуже, чем не объявлять.
 */
export function payoutShare(rank: number, seats: number = PAYOUT_SEATS): number {
  const k = Math.min(Math.trunc(seats), PAYOUT_SEATS);
  if (!Number.isFinite(rank) || rank < 1 || rank > k || k < 1) return 0;
  const weight = k + 1 - Math.trunc(rank);
  const total = (k * (k + 1)) / 2;
  return weight / total;
}

/** Доля места в процентах, округлённая до одного знака — как на сайте. */
export function payoutSharePct(rank: number, seats: number = PAYOUT_SEATS): number {
  return Math.round(payoutShare(rank, seats) * 1000) / 10;
}
